/**
 * Generates the Google OAuth authorization URL for linking a YouTube channel.
 */
export async function connectYouTube(): Promise<YouTubeAuthResponse> {
  const headers = await getAuthHeaders();
  const res = await fetch(`${API_BASE}/auth/youtube`, {
    method: "POST",
    headers,
  });

  if (!res.ok) {
    const errorText = await res.text();
    throw new Error(`YouTube auth failed (${res.status}): ${errorText}`);
  }

  // Clear guest disconnected flag if present when connecting
  if (typeof document !== "undefined") {
    document.cookie = "cutpoint_guest_channel_disconnected=; path=/; max-age=0";
    window.dispatchEvent(new CustomEvent("cutpoint_channel_updated"));
  }

  return res.json();
}

/**
 * Disconnects the linked YouTube channel(s).
 */
export async function disconnectYouTube(channelId?: string): Promise<{ success: boolean; message: string }> {
  const headers = await getAuthHeaders();
  const url = channelId
    ? `${API_BASE}/auth/youtube?channel_id=${encodeURIComponent(channelId)}`
    : `${API_BASE}/auth/youtube`;

  const res = await fetch(url, {
    method: "DELETE",
    headers,
  });

  if (!res.ok) {
    const errorText = await res.text();
    throw new Error(`Failed to disconnect YouTube channel (${res.status}): ${errorText}`);
  }

  // Set guest disconnected cookie flag so demo channels stay disconnected
  if (typeof document !== "undefined") {
    document.cookie = "cutpoint_guest_channel_disconnected=true; path=/; max-age=86400";
    window.dispatchEvent(new CustomEvent("cutpoint_channel_updated"));
  }

  return res.json();
}

