const rawApiUrl = process.env.NEXT_PUBLIC_API_URL || "http://localhost:8000";
export const API_BASE = rawApiUrl.endsWith("/api/v1")
  ? rawApiUrl
  : `${rawApiUrl.replace(/\/$/, "")}/api/v1`;

/**
 * Builds the YouTube OAuth initiation URL pointing to the active backend.
 */
export function getYouTubeAuthUrl(userId?: string): string {
  return `${API_BASE}/auth/youtube${userId ? `?user_id=${encodeURIComponent(userId)}` : ""}`;
}

/**
 * Builds request headers with Supabase JWT bearer or Guest Evaluator header.
 */
async function getAuthHeaders(): Promise<HeadersInit> {
  const headers: Record<string, string> = {
    "Content-Type": "application/json",
  };

  try {
    if (typeof window !== "undefined") {
      const { createClient } = await import("@/lib/supabase/client");
      const supabase = createClient();
      
      // Guard against indefinite lock contention with a 1200ms timeout
      const sessionPromise = supabase.auth.getSession();
      const timeoutPromise = new Promise<{ data: { session: null } }>((resolve) =>
        setTimeout(() => resolve({ data: { session: null } }), 1200)
      );

      const {
        data: { session },
      } = await Promise.race([sessionPromise, timeoutPromise]);

      if (session?.access_token) {
        headers["Authorization"] = `Bearer ${session.access_token}`;
        return headers;
      }
    }
  } catch (err) {
    console.warn("Could not retrieve Supabase session:", err);
  }

  // Fallback to guest evaluator mode
  headers["X-Guest-Session"] = "true";
  headers["Authorization"] = "Bearer guest-evaluator-token";

  if (typeof document !== "undefined" && document.cookie.includes("cutpoint_guest_channel_disconnected=true")) {
    headers["X-Guest-Channel-Disconnected"] = "true";
  }

  return headers;
}


/**
 * Initiates the 8-agent retention forensic analysis pipeline.
 */
export async function startAnalysis(videoId: string): Promise<AnalysisResponse> {
  const headers = await getAuthHeaders();
  const res = await fetch(`${API_BASE}/analyze`, {
    method: "POST",
    headers,
    body: JSON.stringify({ video_id: videoId.trim() }),
  });

  if (!res.ok) {
    const errorText = await res.text();
    throw new Error(`Failed to queue analysis (${res.status}): ${errorText}`);
  }

  return res.json();
}

