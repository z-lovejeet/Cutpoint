/**
 * Streams interactive chat advice token-by-token using Server-Sent Events (SSE).
 */
export async function streamChat(
  analysisId: string,
  message: string,
  onToken: (token: string) => void,
  onError?: (err: Error) => void
): Promise<void> {
  const headers = await getAuthHeaders();

  const response = await fetch(`${API_BASE}/chat`, {
    method: "POST",
    headers,
    body: JSON.stringify({
      analysis_id: analysisId,
      message,
    }),
  });

  if (!response.ok) {
    const errText = await response.text();
    const error = new Error(`Chat stream failed (${response.status}): ${errText}`);
    onError?.(error);
    throw error;
  }

  if (!response.body) {
    throw new Error("No readable stream received from chat endpoint");
  }

  const reader = response.body.getReader();
  const decoder = new TextDecoder();
  let buffer = "";

  try {
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;

      buffer += decoder.decode(value, { stream: true });
      const lines = buffer.split("\n");
      buffer = lines.pop() || "";

      for (const line of lines) {
        const trimmed = line.trim();
        if (!trimmed || !trimmed.startsWith("data:")) continue;

        const dataStr = trimmed.replace(/^data:\s*/, "");
        if (dataStr === "[DONE]") {
          return;
        }

        try {
          const parsed = JSON.parse(dataStr);
          if (parsed.error) {
            const err = new Error(parsed.error);
            onError?.(err);
            throw err;
          }
          if (parsed.token) {
            onToken(parsed.token);
          }
        } catch (e) {
          // If not valid JSON, check if token is raw
          if (e instanceof SyntaxError) {
            continue;
          }
          throw e;
        }
      }
    }
  } finally {
    reader.releaseLock();
  }
}

/**
 * Retrieves chat history for a specific report.
 */
export async function getChatHistory(analysisId: string): Promise<ChatMessage[]> {
  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 3500);

    const headers = await getAuthHeaders();
    const res = await fetch(`${API_BASE}/chat/${analysisId}/history`, {
      method: "GET",
      headers,
      signal: controller.signal,
      cache: "no-store",
    });

    clearTimeout(timeoutId);

    if (!res.ok) {
      return [];
    }

    return await res.json();
  } catch (err) {
    console.warn("Could not retrieve chat history from API:", err);
    return [];
  }
}

